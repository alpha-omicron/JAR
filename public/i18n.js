function t(key) { return I18N[key] || key; }

function applyI18n() {
  document.documentElement.lang = 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  const how = document.getElementById('howEN');
  if (how) how.innerHTML = `<h2>${t('howTitle')}</h2><p>${t('howIntro')}</p><h3>${t('howCardTitle')}</h3><p>${t('howCardText')}</p><h3>${t('howLoreTitle')}</h3><p>${t('howLoreText')}</p><p>${t('howAfter')}</p><ul><li>${t('howLi1')}</li><li>${t('howLi2')}</li></ul><p>${t('howUniverse')}</p>`;
  const saucepan = document.getElementById('howSpEN');
  if (saucepan) saucepan.innerHTML = `<h2>${t('howSaucepanTitle')}</h2><p>${t('howSaucepanText')}</p>`;
}

applyI18n();
